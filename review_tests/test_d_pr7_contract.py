def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def put_json(path, value):
    path.write_text(json.dumps(value, allow_nan=False), encoding="utf-8")


def read_csv(path):
    with path.open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def put_csv(path, rows, fields=None):
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields or list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def refresh_run_hashes(run):
    document = read_json(run / "RUN.json")
    document["output_sha256"] = {
        name: digest((run / name).read_bytes())
        for name in ("queries.csv", "pairs.csv", "match_diagnostics.json")}
    put_json(run / "RUN.json", document)


def reseal_reference(reference):
    document = read_json(reference / "reference_manifest.json")
    document.pop("content_sha256")
    document["files"] = file_specs(reference, list(document["files"]))
    put_json(reference / "reference_manifest.json", seal(document))


