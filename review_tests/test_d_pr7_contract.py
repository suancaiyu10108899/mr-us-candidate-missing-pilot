def test_eight_probe_median_averages_the_middle_two(delivered):
    rotation = np.array([[0., -1., 0.], [1., 0., 0.], [0., 0., 1.]])
    ref = read_json(delivered[1] / "reference.json")
    translation = np.asarray(ref["t"]) + [1.1, -3.3, .4]
    fit_artifacts(delivered, R=rotation.tolist(), t=translation.tolist())
    probes = np.asarray(ref["probes_us"])
    errors = np.linalg.norm(probes @ rotation.T + translation - (probes + ref["t"]), axis=1).tolist()
    assert len(errors) == 8 and sorted(errors)[3] != sorted(errors)[4]
    _, _, metrics = score(delivered)
    assert float(metrics["probe_median"]) == pytest.approx(statistics.median(errors))


