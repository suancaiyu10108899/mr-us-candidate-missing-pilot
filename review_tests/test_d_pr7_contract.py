def score(case):
    release, reference, run, output = case
    result = evaluate(release, run, reference, output)
    return result, read_json(output / "checks.json"), read_csv(output / "metrics.csv")[0]


def rejected_or_failed(case):
    try:
        result, checks, _ = score(case)
    except ValueError:
        return
    assert checks["status"] == "FAIL" and result["checks_ok"] is False


