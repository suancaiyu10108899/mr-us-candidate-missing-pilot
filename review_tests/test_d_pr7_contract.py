def fit_artifacts(case, **changes):
    reference, run = case[1:3]
    ref = read_json(reference / "reference.json")
    transform = {"direction": "US_TO_MR", "unit": "index_unit", "status": "SUCCESS",
                 "R": np.eye(3).tolist(), "t": ref["t"],
                 "pairs_sha256": digest((run / "pairs.csv").read_bytes()), "source_commit": "a" * 40}
    transform.update(changes)
    put_json(run / "transform.json", transform)
    put_json(run / "fit_diagnostics.json", {"status": "SUCCESS", "final_inlier_count": 64,
             "pair_count": 64, "pairs_sha256": transform["pairs_sha256"], "source_commit": "a" * 40})


