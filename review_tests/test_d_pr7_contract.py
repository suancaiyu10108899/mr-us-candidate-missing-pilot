def test_candidate_outside_condition_is_rejected(delivered):
    release, _, run, _ = delivered
    condition = next(c for c in read_json(release / "conditions.json")["conditions"] if c["condition_id"] == "RAND_1")
    kept, removed = condition["keep_ids"][0], condition["remove_ids"][0]
    selected_query = "q" + kept[1:]
    queries = read_csv(run / "queries.csv")
    for query in queries:
        yes = query["query_id"] == selected_query
        query.update(condition_id="RAND_1", accepted="true" if yes else "false",
                     accepted_candidate_id=removed if yes else "")
    put_csv(run / "queries.csv", queries)
    pairs = read_csv(run / "pairs.csv")[:1]
    pairs[0].update(condition_id="RAND_1", query_id=selected_query, candidate_id=removed)
    put_csv(run / "pairs.csv", pairs)
    for name in ("RUN.json", "match_diagnostics.json"):
        document = read_json(run / name)
        document["condition_id"] = "RAND_1"
        put_json(run / name, document)
    refresh_run_hashes(run)
    rejected_or_failed(delivered)


def test_summary_does_not_overwrite_an_existing_report(delivered, tmp_path):
    score(delivered)
    target = tmp_path / "report"
    summarize(delivered[3] / "metrics.csv", delivered[3] / "query_evaluation.csv", target)
    (target / "report.md").write_text("keep this original report", encoding="utf-8")
    with pytest.raises(ValueError):
        summarize(delivered[3] / "metrics.csv", delivered[3] / "query_evaluation.csv", target)
    assert (target / "report.md").read_text(encoding="utf-8") == "keep this original report"


